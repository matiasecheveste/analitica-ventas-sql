-- Esquema relacional de una cadena de comercios con sucursales en Uruguay.

CREATE TABLE departamentos (
  id     smallint PRIMARY KEY,
  nombre text NOT NULL UNIQUE
);

CREATE TABLE sucursales (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          text NOT NULL,
  departamento_id smallint NOT NULL REFERENCES departamentos (id)
);

CREATE TABLE categorias (
  id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre text NOT NULL UNIQUE
);

CREATE TABLE productos (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre       text NOT NULL,
  categoria_id integer NOT NULL REFERENCES categorias (id),
  precio_lista numeric(10, 2) NOT NULL CHECK (precio_lista > 0)
);

CREATE TABLE clientes (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre     text NOT NULL,
  alta       date NOT NULL DEFAULT current_date
);

CREATE TABLE ventas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cliente_id  integer NOT NULL REFERENCES clientes (id),
  sucursal_id integer NOT NULL REFERENCES sucursales (id),
  fecha       date NOT NULL
);

CREATE TABLE lineas_venta (
  venta_id        bigint  NOT NULL REFERENCES ventas (id) ON DELETE CASCADE,
  producto_id     integer NOT NULL REFERENCES productos (id),
  cantidad        integer NOT NULL CHECK (cantidad > 0),
  -- El precio se copia al vender: los cambios de lista no alteran ventas pasadas.
  precio_unitario numeric(10, 2) NOT NULL CHECK (precio_unitario > 0),
  importe         numeric(12, 2) GENERATED ALWAYS AS (cantidad * precio_unitario) STORED,
  PRIMARY KEY (venta_id, producto_id)
);

-- Índices pensados para las consultas de consultas/*.sql
CREATE INDEX ventas_fecha_idx ON ventas (fecha);
CREATE INDEX ventas_cliente_fecha_idx ON ventas (cliente_id, fecha);
CREATE INDEX lineas_producto_idx ON lineas_venta (producto_id);

